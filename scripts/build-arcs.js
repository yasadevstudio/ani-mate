#!/usr/bin/env node
// YASA PRESENTS
// build-arcs.js — generate mobile/www/js/arcs.js from server/arcs.json.
//
// ONE SOURCE OF TRUTH. server/arcs.json is the master. The server reads it at
// runtime; mobile cannot, because it is a packaged web app that talks to AllAnime
// directly and never calls our server. So mobile gets a generated JS file instead
// of a second hand-maintained copy that would drift.
//
// Run after editing server/arcs.json:   node scripts/build-arcs.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const raw = JSON.parse(fs.readFileSync(path.join(root, 'server/arcs.json'), 'utf8'));

const out = {};
let dropped = 0;
for (const [id, v] of Object.entries(raw)) {
    if (id.startsWith('_') || !v || !Array.isArray(v.arcs) || !v.arcs.length) continue;
    const a = v.arcs;
    let ok = a[0].from === 1 && a[a.length - 1].to === v.episodes;
    for (let i = 0; i < a.length - 1; i++) if (a[i + 1].from !== a[i].to + 1) ok = false;
    if (!ok) { console.warn(`  DROPPED ${v.title || id}: ranges not contiguous 1..${v.episodes}`); dropped++; continue; }
    out[id] = { episodes: v.episodes, arcs: a.map(x => ({ name: x.name, from: x.from, to: x.to })) };
}

const js = `// GENERATED by scripts/build-arcs.js from server/arcs.json — do not edit.
// Story arcs keyed by AniList id. Validated at build time: contiguous from 1 and
// ending at the episode count, because a wrong boundary is worse than none.
window.ANIMATE_ARCS = ${JSON.stringify(out, null, 2)};
`;
const dest = path.join(root, 'mobile/www/js/arcs.js');
fs.writeFileSync(dest, js);
console.log(`  wrote ${path.relative(root, dest)} — ${Object.keys(out).length} series, ${dropped} dropped`);
